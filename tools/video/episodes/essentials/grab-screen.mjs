// Grabs one still of the live Essentials app and writes it as a data: URI.
//
// A data URI, not a .png next to the page, on purpose. An image loaded through
// img.src under file:// taints the canvas permanently, and from then on every
// getImageData on it throws — which would break the pixel assertions in
// tests/video/03-cast.cjs and 04-art.cjs the moment this episode is rendered.
// A data: URI does not taint. This is a documented trap in this repo.
//
//   node grab-screen.mjs [url]
//
// The default target is the officials list for Los Angeles City Hall. The
// address is a public building on purpose: the still ships in the episode, and
// nobody's home address belongs in it. Los Angeles is one of the curated alpha
// communities, so the list that comes back runs city council to Congress —
// which is the thing chapter 8 is pointing at. A fresh browser needs no
// profile here: the address is in the URL and the answer is public.

import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const HERE = path.dirname(fileURLToPath(import.meta.url));
const ADDRESS = '200 N Spring St, Los Angeles, CA 90012';
const TARGET = process.argv.slice(2).filter(a => !a.startsWith('--'))[0]
  || 'https://essentials.empowered.vote/results?q=' + encodeURIComponent(ADDRESS);

const DARK = () => { try { localStorage.setItem('ev:color-scheme', 'dark'); } catch (e) { /* private mode */ } };

const { chromium } = require('playwright');
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.addInitScript(DARK);
await page.goto(TARGET, { waitUntil: 'networkidle' });

// The list is fetched after the first paint, so networkidle alone can catch
// the skeleton. Wait for a real office to be named, then let the portraits
// land. Waiting on a level-2 heading was tried first and always timed out —
// the results page builds its groups out of divs — so every run printed a
// warning that the still might be a skeleton while writing a perfect one. A
// check that cries wolf on a good run is worse than no check.
try {
  await page.getByText(/Mayor|City Council|Representative/).first().waitFor({ timeout: 20000 });
} catch (e) {
  console.warn('no office was named within 20s — look at the still before trusting it');
}
await page.waitForTimeout(3000);

// A TALL still, not a viewport one. The close holds this picture for thirteen
// seconds, and a static frame for thirteen seconds is a slide. The draw
// function pans down it instead, so the viewer sees the roster arrive the way
// a person scrolling the real page would.
// JPEG, not PNG, and this is a size decision rather than a quality one.
// screen.js is COMMITTED — a fresh checkout has to build the same episode —
// and render.yaml serves the whole repo, so this file ships on every deploy.
// The same capture is 996 KB as a PNG and 310 KB at this quality, and the
// content is a photograph of a skyline and twelve portraits, which is what
// JPEG is for. Text in the frame was compared at 1:1 before the switch.
const buf = await page.screenshot({ type: 'jpeg', quality: 92, fullPage: true,
  clip: { x: 0, y: 0, width: 1440, height: 2100 } });
await browser.close();

await writeFile(path.join(HERE, 'screen.js'),
  '// GENERATED by grab-screen.mjs. Re-run it to refresh the still.\n' +
  '// Source: ' + TARGET + '\n' +
  'window.EVEssentialsShot = "data:image/jpeg;base64,' + buf.toString('base64') + '";\n',
  'utf8');
console.log('wrote screen.js,', Math.round(buf.length / 1024), 'KB from', TARGET);
