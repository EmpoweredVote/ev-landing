// Grabs one still of the live Compass app and writes it as a data: URI.
//
// A data URI, not a .png next to the page, on purpose. An image loaded through
// img.src under file:// taints the canvas permanently, and from then on every
// getImageData on it throws — which would break the pixel assertions in
// tests/video/03-cast.cjs and 04-art.cjs the moment this episode is rendered.
// A data: URI does not taint. This is a documented trap in this repo.
//
//   node grab-screen.mjs [url] [--profile <chrome user-data-dir>]
//
// A fresh browser reaches only the calibration onboarding screen, because a
// compass that nobody has answered has no shape to draw. --profile borrows a
// browser profile that HAS answered, so the still shows a real calibrated
// radar. Point it at a COPY of the profile, never the live one: Chrome holds a
// single-instance lock on a directory it is running in, and the copy keeps this
// script from writing anything into a browser somebody is using. Only four
// things need to come across — `Local State`, `Default/Preferences`,
// `Default/Network/Cookies` and `Default/Local Storage/leveldb`.

import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const HERE = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const pi = args.indexOf('--profile');
const PROFILE = pi >= 0 ? args[pi + 1] : null;
const TARGET = args.filter((a, i) => i !== pi && i !== pi + 1 && !a.startsWith('--'))[0]
  || 'https://compass.empowered.vote/';

const DARK = () => { try { localStorage.setItem('ev:color-scheme', 'dark'); } catch (e) { /* private mode */ } };

const { chromium } = require('playwright');
let ctx, page, close;
if (PROFILE) {
  ctx = await chromium.launchPersistentContext(PROFILE,
    { channel: 'chrome', headless: true, viewport: { width: 1440, height: 900 } });
  page = ctx.pages()[0] || await ctx.newPage();
  close = () => ctx.close();
} else {
  const browser = await chromium.launch();
  page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  close = () => browser.close();
}
await page.addInitScript(DARK);
await page.goto(TARGET, { waitUntil: 'networkidle' });
await page.waitForTimeout(2500);                 // let any chart finish drawing

// A returning profile gets the coach-mark tour, which dims the whole page
// behind it. Dismiss it before anything else, or the still is a screenshot of
// the tutorial over a greyed-out compass.
for (const name of [/^Skip All$/i, /^Skip$/i, /^Got it$/i]) {
  try { await page.getByRole('button', { name }).first().click({ timeout: 1500 }); } catch (e) { /* not shown */ }
}
await page.waitForTimeout(800);

// The sign-up prompt is correct product behaviour and wrong for a still: it is
// the one element in the frame that is about us rather than about the compass.
//
// Match the SMALLEST element that carries the text. Every ancestor up to the
// root also contains it, so hiding everything that matches hides the whole app
// and writes a blank white still that still looks like a successful run.
await page.evaluate(() => {
  const re = /Save your compass results/i;
  const all = [...document.querySelectorAll('div,section,aside')]
    .filter(el => re.test(el.textContent || ''));
  const innermost = all.filter(el => !all.some(o => o !== el && el.contains(o)));
  for (const el of innermost) el.style.visibility = 'hidden';
  return innermost.length;
});
await page.waitForTimeout(300);

const buf = await page.screenshot({ type: 'png' });
await close();

await writeFile(path.join(HERE, 'screen.js'),
  '// GENERATED by grab-screen.mjs. Re-run it to refresh the still.\n' +
  '// Source: ' + TARGET + (PROFILE ? ' (calibrated profile)' : ' (fresh browser)') + '\n' +
  'window.EVCompassShot = "data:image/png;base64,' + buf.toString('base64') + '";\n',
  'utf8');
console.log('wrote screen.js,', Math.round(buf.length / 1024), 'KB from', TARGET);
