// Regenerate the Fallacy Finders card artwork block that ev-figures.js draws with Path2D.
//
// Why Path2D and not an <img> of the SVG: drawing an SVG loaded by `src` onto a canvas TAINTS it
// under file://, and the whole test suite runs from file://. Once tainted, every later
// getImageData on that canvas throws SecurityError — including the one in
// tests/layout/beam-clears-metarow.cjs, which reads the beam crew's canvas. Path data carries no
// origin, so it cannot taint anything. (A data: URI also avoids the taint, but costs ~31KB of
// encoded blob for both variants; one shared geometry plus two palettes is less than half that.)
//
// The two brand SVGs differ only in the teal, plus sub-0.001-unit floating point noise in a
// 453-unit viewBox. So we keep ONE geometry, tag each path with a colour ROLE, and swap palettes.
//
// Usage:  node tools/gen-fallacy-card-art.mjs        (prints the block to paste into ev-figures.js)
//         node tools/gen-fallacy-card-art.mjs --check (verifies the two SVGs still agree)
import { readFileSync } from 'node:fs';

const SRC_LIGHT = 'icons/fallacy-finders-logo-lg-light.svg';
const SRC_DARK = 'icons/fallacy-finders-logo-lg-dark.svg';
// 1dp, not 2. The two brand variants disagree by up to 0.005 units in places (8.82 vs 8.83), which
// survives 2dp rounding and would block sharing one geometry. At 1dp they agree exactly, and 0.05
// units of a 453-unit viewBox is 0.02px once the lockup is drawn ~171px wide — invisible. The SVGs
// in icons/ keep full precision; this only affects the canvas copy.
const PRECISION = 1;

// brand palette; the roles are what each path is tagged with
const ROLE_OF = {
  '#FF5740': 'coral',
  '#00657C': 'ink',      // the wordmark teal, light theme
  '#59B0C4': 'ink',      // ...and dark theme
  '#FFD426': 'spark'
};

function parse(file) {
  const s = readFileSync(file, 'utf8');
  // A general viewBox, not "0 0 w h": these lockups carry padding that normalises them into the
  // family of five (the raw brand art runs flush to its box, so its symbol stuck ~27px further
  // right than the others and read a size larger). The padding is expressed as a viewBox offset so
  // no path is touched, which means the card has to honour the origin when it draws.
  const vb = s.match(/viewBox="(-?[\d.]+) (-?[\d.]+) ([\d.]+) ([\d.]+)"/);
  if (!vb) throw new Error(file + ': no viewBox');
  const paths = [];
  const re = /<path([^>]*?)\/>/g;
  let m;
  while ((m = re.exec(s))) {
    const attrs = m[1];
    const d = (attrs.match(/\sd="([^"]*)"/) || [])[1];
    const fill = (attrs.match(/fill="([^"]*)"/) || [])[1];
    if (!d || !fill) throw new Error(file + ': path missing d or fill');
    paths.push({
      d: d.replace(/-?\d+\.\d+/g, n => String(+(+n).toFixed(PRECISION))),
      fill,
      evenodd: /fill-rule="evenodd"/.test(attrs)
    });
  }
  return { x0: +vb[1], y0: +vb[2], w: +vb[3], h: +vb[4], paths };
}

const light = parse(SRC_LIGHT);
const dark = parse(SRC_DARK);

if (light.paths.length !== dark.paths.length) {
  throw new Error(`path count differs: ${light.paths.length} light vs ${dark.paths.length} dark`);
}
// Geometry must agree once rounded. If a future brand update actually reshapes one variant, this
// throws rather than silently shipping the light shapes in dark mode.
const drift = light.paths
  .map((p, i) => (p.d === dark.paths[i].d ? null : i))
  .filter(i => i !== null);
if (drift.length) {
  throw new Error('geometry differs beyond rounding at path indices ' + drift.join(', ') +
    ' — the variants can no longer share one geometry.');
}

const palette = { light: {}, dark: {} };
light.paths.forEach((p, i) => {
  const role = ROLE_OF[p.fill.toUpperCase()];
  if (!role) throw new Error('unmapped light fill ' + p.fill + ' at path ' + i);
  palette.light[role] = p.fill.toUpperCase();
  const droll = ROLE_OF[dark.paths[i].fill.toUpperCase()];
  if (droll !== role) throw new Error('role mismatch at path ' + i);
  palette.dark[role] = dark.paths[i].fill.toUpperCase();
});

if (process.argv.includes('--check')) {
  console.log('OK — ' + light.paths.length + ' paths, geometry shared, roles ' +
    Object.keys(palette.light).join('/'));
  console.log('light', JSON.stringify(palette.light));
  console.log('dark ', JSON.stringify(palette.dark));
  process.exit(0);
}

const roles = light.paths.map(p => ROLE_OF[p.fill.toUpperCase()]);
const eo = light.paths.map((p, i) => (p.evenodd ? i : null)).filter(i => i !== null);

const lines = [];
lines.push('    // ── Fallacy Finders lockup, as canvas path data ────────────────────────────────────');
lines.push('    // GENERATED by tools/gen-fallacy-card-art.mjs from icons/fallacy-finders-logo-lg-*.svg.');
lines.push('    // Do not hand-edit; re-run the tool if the brand artwork changes.');
lines.push('    //');
lines.push('    // Path data rather than an <img> of the SVG on purpose: an SVG loaded by `src` and drawn to a');
lines.push('    // canvas TAINTS it under file://, and every pixel test in tests/ runs from file:// — a tainted');
lines.push('    // beam canvas makes tests/layout/beam-clears-metarow.cjs throw SecurityError forever. Path data');
lines.push('    // has no origin, so it cannot taint. The two brand variants share one geometry and differ only');
lines.push('    // in the wordmark teal, so the colours are ROLES resolved per theme.');
lines.push(`    var FF_ART = { x0: ${light.x0}, y0: ${light.y0}, w: ${light.w}, h: ${light.h},`);
lines.push('      light: ' + JSON.stringify(palette.light) + ',');
lines.push('      dark: ' + JSON.stringify(palette.dark) + ',');
lines.push('      evenodd: ' + JSON.stringify(eo) + ',');
lines.push('      roles: ' + JSON.stringify(roles) + ',');
lines.push('      d: [');
light.paths.forEach((p, i) => {
  lines.push("        '" + p.d + "'" + (i === light.paths.length - 1 ? '' : ','));
});
lines.push('      ] };');
lines.push('    var FF_PATHS = null;   // lazily built Path2D objects, one per entry in FF_ART.d');

const block = lines.join('\n');
console.log(block);
process.stderr.write('\n[' + (Buffer.byteLength(block) / 1024).toFixed(1) + 'KB, ' +
  light.paths.length + ' paths]\n');
